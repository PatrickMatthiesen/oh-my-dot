func ohMyPoshThemeNames() []string {
	names := make([]string, 0, len(ohMyPoshThemeFiles))
	for name := range ohMyPoshThemeFiles {
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

func ohMyPoshThemeFile(name string) string {
	if filename, ok := ohMyPoshThemeFiles[name]; ok {
		return filename
	}
	// Preserve rendering of existing manifests with safe, unlisted theme names.
	return name + ".omp.json"
}
